export const LEAN_TOOL_IDS = tools.filter((t) => t.stack === "lean" && t.recommended).map((t) => t.id)

export function monthlyStackCost(stack: Tool["stack"] | "all") {
  const set = new Set<string>()
  return tools
    .filter((t) => {
      if (stack === "all") return t.recommended
      if (stack === "lean") return t.stack === "lean" && t.recommended
      if (stack === "growth") return (t.stack === "lean" || t.stack === "growth") && t.recommended
      return t.recommended && t.stack !== "optional"
    })
    .filter((t) => {
      if (set.has(t.id)) return false
      set.add(t.id)
      return true
    })
    .reduce((sum, t) => sum + t.monthlyUsd, 0)
}
